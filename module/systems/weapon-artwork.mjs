const SCOPE = 'Immortals-system';

/** Resolve only authentic Ascension source art, preserving a supplied custom image. */
export function weaponArtworkForImport(source) {
  if (source?.type !== 'weapon') return null;
  const entry = WEAPON_ARTWORK.find(e => e.origin === source._id);
  return entry && [entry.previous, entry.image].includes(source.img) ? entry.image : null;
}

/** Patch portraits alone; random IDs of inventory copies are resolved through import metadata. */
export function prepareWeaponArtworkUpdate(item) {
  if (!item || item.isOwner === false || item.limited === true) return null;
  const owner = item.actor ?? (['character', 'npc'].includes(item.parent?.type) ? item.parent : null);
  if (owner && (owner.isOwner !== true || owner.limited === true)) return null;
  const source = item.toObject?.() ?? item;
  if (source.type !== 'weapon') return null;
  const imported = source.flags?.[SCOPE]?.ascensionImport;
  if (imported && (imported.system !== 'ascension-system' || imported.pack !== 'equipment'
    || imported.sourceType !== 'weapon')) return null;
  const id = source._id ?? item.id;
  const entry = WEAPON_ARTWORK.find(e => imported ? e.origin === imported.documentId : e.id === id);
  if (!entry || !id || source.system?.type?.value !== entry.type
    || ![entry.previous, entry.image].includes(source.img)) return null;
  const patch = {_id: id};
  if (source.img === entry.previous) patch.img = entry.image;
  for (const [key, activity] of Object.entries(source.system?.activities ?? {})) {
    if (!/^[A-Za-z0-9]{1,64}$/u.test(key) || ['constructor', 'prototype', '__proto__'].includes(key)) continue;
    if (activity.img === entry.previous) patch['system.activities.' + key + '.img'] = entry.image;
  }
  if (Object.keys(patch).length === 1) return null;
  patch['flags.' + SCOPE + '.weaponArtworkVersion'] = 1;
  return patch;
}
